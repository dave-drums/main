"""Render shared navigation into the static pages; no website build/runtime dependency.

Edit build/config/navigation.json for links, or the render functions here for markup.
Run this script to update all pages. Use --check to report stale generated markup.
"""

import argparse
import json
import os
import re
from html import escape
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
HEADER = re.compile(r'<header\b[^>]*class="site-header"[^>]*>.*?</header>', re.S)
FOOTER = re.compile(r'<footer\b[^>]*class="site-footer section-shell"[^>]*>.*?</footer>', re.S)


def current_page(path):
    relative = path.relative_to(ROOT).as_posix()
    if relative.startswith("notation/") and relative.endswith(".html"):
        return "/" + relative.removesuffix(".html")
    return "/" + relative.removesuffix("index.html")


def icon(name, css=""):
    classes = " ".join(filter(None, ("icon", css)))
    return f'<svg aria-hidden="true" class="{classes}" focusable="false"><use href="/assets/icons.svg#{name}"></use></svg>'


def link(item, current, contact=False, show_icon=True):
    active = ' aria-current="page"' if item["href"] == current else ""
    if not active and item["href"] != "/" and item["href"].endswith("/") and current.startswith(item["href"]):
        active = ' aria-current="location"'
    css = ' class="nav-contact"' if contact else ""
    arrow = " " + icon("arrow-up-right") if contact else ""
    service_icons = {"/lessons/": "drum", "/recording/": "waveform", "/metronome/": "metronome", "/groove/": "grid", "/rudiments/": "sticks", "/rhythm/": "rhythm", "/notation/karnivool-drone": "book"}
    prefix = icon(service_icons[item["href"]]) + " " if show_icon and item["href"] in service_icons else ""
    return f'<a{active}{css} href="{escape(item["href"], quote=True)}">{prefix}{escape(item["label"])}{arrow}</a>'


def group_active(group, current):
    return any(
        current == item["href"]
        or (item["href"] != "/" and item["href"].endswith("/") and current.startswith(item["href"]))
        for item in group["links"]
    )


def render_header(config, current):
    direct = {item["id"]: item for item in config["direct"]}
    parts = [
        '<header class="site-header">',
        '   <!-- Generated by build/authoring/sync-navigation.py from build/config/navigation.json. -->',
        '   <a aria-label="Dave Drums home" class="brand" href="/">',
        '    <img alt="Dave Drums" height="97" src="/img/dd-logo-320.webp" width="320"/>',
        '   </a>',
        '   <button aria-controls="site-navigation" aria-expanded="false" aria-label="Open navigation" class="nav-toggle" type="button">',
        '    Menu <span aria-hidden="true" class="menu-symbol">' + icon("menu", "menu-open-icon") + icon("close", "menu-close-icon") + '</span>',
        '   </button>',
        '   <span hidden="" id="nav-current-section">Current section</span>',
        '   <nav aria-label="Main navigation" id="site-navigation">',
        '    ' + link(direct["home"], current, show_icon=False),
        '    ' + link(direct["about"], current, show_icon=False),
    ]
    parts.extend('    ' + link(item, current, show_icon=False) for key, item in direct.items()
                 if key not in ("home", "about", "contact"))
    for group in config["groups"]:
        key = group["id"]
        active = group_active(group, current)
        css = "nav-group is-current" if active else "nav-group"
        description = ' aria-describedby="nav-current-section"' if active else ""
        parts.extend([
            f'    <details class="{css}">',
            f'     <summary aria-controls="nav-{key}"{description} class="nav-disclosure">{escape(group["label"])} <span aria-hidden="true" class="nav-caret">{icon("chevron-down")}</span></summary>',
            f'     <ul class="nav-submenu" id="nav-{key}">',
        ])
        parts.extend('      <li>' + link(item, current) + '</li>' for item in group["links"])
        parts.extend(['     </ul>', '    </details>'])
    parts.extend([
        '    ' + link(direct["contact"], current, contact=True),
        '   </nav>',
        '  </header>',
    ])
    return "\n".join(parts)


def render_footer(config, current):
    tools = next(group for group in config["groups"] if group["id"] == "tools")
    rows = [
        ("Explore", config["direct"]),
        ("Free tools", [item for item in tools["links"] if item["href"] != "/notation/karnivool-drone"]),
    ]
    parts = [
        '<footer class="site-footer section-shell">',
        '   <!-- Generated by build/authoring/sync-navigation.py from build/config/navigation.json. -->',
        '   <div class="footer-identity">',
        '    <a aria-label="Dave Drums home" class="footer-brand" href="/">',
        '     <img alt="Dave Drums" height="97" loading="lazy" src="/img/dd-logo-320.webp" width="320"/>',
        '    </a>',
        '    <p class="footer-signature">A life in <em class="editorial-word">rhythm.</em></p>',
        '    <p class="footer-location">' + icon("pin") + ' Melbourne, Australia</p>',
        '   </div>',
        '   <div class="footer-links">',
        '    <nav aria-label="Footer navigation" class="footer-navigation">',
    ]
    for label, items in rows:
        parts.append(f'     <ul class="footer-menu" aria-label="{escape(label)}">')
        for index, item in enumerate(items):
            separator = '<span class="footer-separator" aria-hidden="true">&#8226;</span>' if index else ''
            parts.append('      <li>' + separator + link(item, current, show_icon=False) + '</li>')
        parts.append('     </ul>')
    parts.extend([
        '    </nav>',
        '    <p class="footer-copyright"><span>&#169; 2026 Dave D&#8217;Amore</span> <span class="footer-credit"><span aria-hidden="true">&#8226;</span> Built by <a href="https://www.monoweb.com.au/" target="_blank" rel="noopener noreferrer" aria-label="MonoWeb (opens in a new tab)">MonoWeb</a></span></p>',
        '   </div>',
        '   <div class="footer-actions">',
        '    <a class="footer-top" href="#top">Back to top ' + icon("arrow-up") + '</a>',
        '   </div>',
        '  </footer>',
    ])
    return "\n".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Exit unsuccessfully if any page needs syncing.")
    args = parser.parse_args()
    config = json.loads((ROOT / "build/config/navigation.json").read_text(encoding="utf-8"))
    for group in config["groups"]:
        if not re.fullmatch(r"[a-z][a-z0-9-]*", group["id"]):
            raise ValueError("Navigation group IDs must be valid HTML ID suffixes.")
    items = [*config["direct"], *(item for group in config["groups"] for item in group["links"])]
    if any(not item["href"].startswith("/") or item["href"].startswith("//") for item in items):
        raise ValueError("Navigation destinations must be root-relative local URLs.")
    changed = []
    count = 0
    pages = []
    for folder, directories, names in os.walk(ROOT):
        relative = Path(folder).relative_to(ROOT).as_posix()
        directories[:] = [name for name in directories
                          if not name.startswith(".") and name not in
                          {"node_modules", "apps", "build", "dist", "help", "__pycache__"}
                          and not (name == "app" and relative in {"metronome", "groove"})]
        pages.extend(Path(folder) / name for name in names if name.endswith(".html"))
    for path in sorted(pages):
        source = path.read_bytes().decode("utf-8")
        if not HEADER.search(source) and not FOOTER.search(source):
            continue
        current = current_page(path)
        updated, headers = HEADER.subn(lambda _: render_header(config, current), source)
        updated, footers = FOOTER.subn(lambda _: render_footer(config, current), updated)
        if headers != 1 or footers != 1:
            raise ValueError(f"{path.relative_to(ROOT)} must contain exactly one shared header and footer.")
        # Load the one shared interaction module using each document's existing asset prefix.
        if not re.search(r'src="[^\"]*assets/navigation\.js"', updated):
            updated, scripts = re.subn(
                r'(<script\b[^>]*src="([^\"]*assets/)script\.js"[^>]*>\s*</script>)',
                lambda m: m[0] + f'\n  <script defer="" src="{m[2]}navigation.js"></script>',
                updated,
            )
            if scripts != 1:
                raise ValueError(f"Cannot locate the shared script in {path.relative_to(ROOT)}.")
        count += 1
        if updated != source:
            changed.append(path.relative_to(ROOT).as_posix())
            if not args.check:
                path.write_bytes(updated.encode("utf-8"))
    if args.check and changed:
        print("Navigation needs syncing: " + ", ".join(changed))
        return 1
    print(f"{'Checked' if args.check else 'Synced'} shared navigation on {count} pages.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
