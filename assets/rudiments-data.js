// All 40 PAS International Drum Rudiments; expanded playback of the PAS figures.
// Sources: https://pas.org/wp-content/uploads/2024/04/pas-rudiments.pdf
// https://ae.vicfirth.com/education/40-essential-rudiments/
// Compressed rolls are expanded into actual strokes. #4 uses measured hand-change
// guides for uncounted buzz rebounds; measured rolls use thirty-second strokes.
// Lower alternative stickings on the PAS chart are selected with Lead hand.
// One quarter = 96 ticks. "t" = 3:2; "s" = 6:4; "." = dotted.
export const TICKS_PER_BEAT = 96;
const swap = (hand) => hand === 'R' ? 'L' : hand === 'L' ? 'R' : null;
function sequence(hands, values = 16, { accents = [], flams = [], drags = [], tupletUnit, buzz = false } = {}) {
  return [...hands].map((hand, index) => {
    const spec = String(Array.isArray(values) ? values[index] : values);
    const value = parseInt(spec, 10);
    const tuplet = spec.includes('s') ? 6 : spec.includes('t') ? 3 : 0;
    const dot = spec.includes('.');
    const ticks = TICKS_PER_BEAT * 4 / value * (tuplet ? 2 / 3 : 1) * (dot ? 1.5 : 1);
    const graceCount = drags.includes(index) ? 2 : flams.includes(index) ? 1 : 0;
    return { hand: hand === '-' ? null : hand, value, ticks, beats: ticks / TICKS_PER_BEAT,
      accent: accents.includes(index), grace: Array(graceCount).fill(swap(hand)),
      tuplet, tupletUnit: tupletUnit || value, dot, buzz };
  });
}
const mirror = (notes) => notes.map((n) => ({ ...n, hand: swap(n.hand), grace: n.grace.map(swap) }));
const both = (notes) => [...notes, ...mirror(notes)];
const twice = (notes) => [...notes, ...notes.map((n) => ({ ...n, grace: [...n.grace] }))];
const openRoll = (count, rolledValue, releaseValue) => {
  const hands = 'RRLL'.repeat(Math.ceil(count / 4)).slice(0, count - 1);
  return sequence(hands + swap(hands.at(-1)), [...Array(count - 1).fill(rolledValue), releaseValue], {
    accents: [count - 1], tupletUnit: String(rolledValue).includes('t') ? parseInt(rolledValue, 10) : undefined,
  });
};
